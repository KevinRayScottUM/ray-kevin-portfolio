import {readFileSync,writeFileSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
const source=new URL('../data/locales.json',import.meta.url),target=new URL('../static/js/locales/catalog.js',import.meta.url);
execFileSync(process.env.PYTHON||'python3',[new URL('./validate-locale-json.py',import.meta.url).pathname,source.pathname],{stdio:'pipe'});
const messages=JSON.parse(readFileSync(source,'utf8'));
for(const [key,pair] of Object.entries(messages)){
  if(!/^[a-z][\w.-]+$/.test(key))throw Error('Invalid translation key: '+key);
  for(const lang of ['en','zh-CN'])if(typeof pair[lang]!=='string'||!pair[lang])throw Error(`Missing ${lang}: ${key}`);
  const slots=s=>[...s.matchAll(/\{(\w+)\}/g)].map(m=>m[1]).sort().join(',');
  if(slots(pair.en)!==slots(pair['zh-CN']))throw Error('Placeholder mismatch: '+key);
}
const output='// Generated by tools/build-locales.mjs from data/locales.json.\nexport default '+JSON.stringify(messages,null,2)+';\n';
if(process.argv.includes('--check')){if(readFileSync(target,'utf8')!==output)throw Error('Run node tools/build-locales.mjs');}
else writeFileSync(target,output);
console.log(`${Object.keys(messages).length} bilingual messages validated.`);
